struct InsertResult {
    let ok: Bool
    let method: String        // "accessibility" | "paste" | "none"
    let error: String?
}

enum Inserter {
    static func insert(_ text: String, into pid: pid_t, appName: String) -> InsertResult {
        if text.isEmpty { return InsertResult(ok: false, method: "none", error: "empty transcript") }
        if Perms.secureInput() {
            return InsertResult(ok: false, method: "none",
                                error: "secure input is on (a password field, or Terminal's "
                                     + "Secure Keyboard Entry) — macOS blocks inserted text there")
        }
        // Never type into a different app than the one that was frontmost when
        // the hotkey went down.
        let front = NSWorkspace.shared.frontmostApplication?.processIdentifier
        if front != pid {
            return InsertResult(ok: false, method: "none",
                                error: "focus left \(appName) while you were speaking — "
                                     + "nothing was inserted")
        }
        if AXIsProcessTrusted(), axInsert(text, pid: pid) {
            return InsertResult(ok: true, method: "accessibility", error: nil)
        }
        if pasteInsert(text) {
            return InsertResult(ok: true, method: "paste", error: nil)
        }
        return InsertResult(ok: false, method: "none",
                            error: "could not insert the text (no editable field had focus)")
    }

    // --- Accessibility --------------------------------------------------
    private static func axInsert(_ text: String, pid: pid_t) -> Bool {
        let app = AXUIElementCreateApplication(pid)
        var focusedRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(app, kAXFocusedUIElementAttribute as CFString,
                                            &focusedRef) == .success,
              let focused = focusedRef, CFGetTypeID(focused) == AXUIElementGetTypeID()
        else { return false }
        let element = unsafeBitCast(focused, to: AXUIElement.self)

        // 1. Replace the selection.  This is one call and works in AppKit,
        //    Catalyst and most native text views.
        if AXUIElementSetAttributeValue(element, kAXSelectedTextAttribute as CFString,
                                        text as CFTypeRef) == .success {
            return true
        }

        // 2. Splice into the value at the selected range.  Electron/CEF fields
        //    that expose a value but refuse a selected-text write land here.
        var valueRef: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXValueAttribute as CFString,
                                            &valueRef) == .success,
              let value = valueRef as? String
        else { return false }

        var rangeRef: CFTypeRef?
        var loc = value.count
        var len = 0
        if AXUIElementCopyAttributeValue(element, kAXSelectedTextRangeAttribute as CFString,
                                         &rangeRef) == .success,
           let r = rangeRef, CFGetTypeID(r) == AXValueGetTypeID() {
            var cf = CFRange(location: 0, length: 0)
            if AXValueGetValue(unsafeBitCast(r, to: AXValue.self), .cfRange, &cf) {
                loc = max(0, min(value.count, cf.location))
                len = max(0, min(value.count - loc, cf.length))
            }
        }
        let chars = Array(value)
        let head = String(chars[0..<loc])
        let tail = String(chars[(loc + len)...])
        let merged = head + text + tail
        guard AXUIElementSetAttributeValue(element, kAXValueAttribute as CFString,
                                           merged as CFTypeRef) == .success
        else { return false }
        // Put the caret after what we inserted; a field that refuses this is
        // still correctly filled, so the return value is deliberately ignored.
        var after = CFRange(location: loc + text.count, length: 0)
        if let axr = AXValueCreate(.cfRange, &after) {
            _ = AXUIElementSetAttributeValue(element, kAXSelectedTextRangeAttribute as CFString, axr)
        }
        return true
    }

    // --- clipboard + Cmd-V ----------------------------------------------
    //
    // Two rules the clipboard half keeps.
    //
    // (1) CONCEALED.  A dictated sentence is private speech, so the item we put
    //     on the pasteboard declares org.nspasteboard.ConcealedType (and
    //     AutoGeneratedType): the community convention every clipboard manager
    //     honours by not archiving the item.  Without it, "clipboard history
    //     off" is a setting we would be trusting on the user's behalf.
    //
    // (2) THE USER'S COPY WINS.  The old restore fired unconditionally half a
    //     second later, so a Cmd-C made inside that window was destroyed.  The
    //     pasteboard's `changeCount` at the moment we wrote is remembered, and
    //     the restore happens only while it still holds — anything else means
    //     someone else owns the clipboard now.

    static let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let autoGeneratedType =
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private typealias Snapshot = [[NSPasteboard.PasteboardType: Data]]

    private struct PendingRestore {
        let pb: NSPasteboard
        let saved: Snapshot
        let changeCount: Int
    }

    private static let pendingLock = NSLock()
    private static var pending: PendingRestore?

    static var hasPendingRestore: Bool {
        pendingLock.lock(); defer { pendingLock.unlock() }
        return pending != nil
    }

    /// Write `text` as one concealed, auto-generated pasteboard item.
    @discardableResult
    static func writeConcealed(_ text: String, to pb: NSPasteboard) -> Bool {
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return false }
        // Marker types: their PRESENCE is the whole signal, the payload is never
        // read, so an empty string is the conventional value.
        if !item.setString("", forType: concealedType)
            || !item.setString("", forType: autoGeneratedType) {
            log("could not mark the clipboard item concealed")
        }
        pb.clearContents()
        return pb.writeObjects([item])
    }

    /// Leave `text` on the general pasteboard for the user to paste themselves.
    /// Used whenever insertion is refused: words that cannot be typed must not
    /// simply vanish, and they are still concealed on the way out.
    @discardableResult
    static func offerOnClipboard(_ text: String) -> Bool {
        if text.isEmpty { return false }
        clearPending()          // nothing may restore over what we are about to write
        return writeConcealed(text, to: NSPasteboard.general)
    }

    /// Put back what was on the pasteboard before the paste — but only while it
    /// is still what we wrote.  Called on a timer after every paste and once
    /// more from `applicationWillTerminate`, so a helper that quits inside the
    /// window does not leave the dictated text behind.
    static func flushPendingRestore() {
        pendingLock.lock()
        let job = pending
        pending = nil
        pendingLock.unlock()
        guard let job = job else { return }
        guard job.pb.changeCount == job.changeCount else {
            log("the clipboard changed while pasting — leaving the newer copy alone")
            return
        }
        restore(job.pb, job.saved)
    }

    private static func setPending(_ pb: NSPasteboard, _ saved: Snapshot, _ changeCount: Int) {
        pendingLock.lock()
        pending = PendingRestore(pb: pb, saved: saved, changeCount: changeCount)
        pendingLock.unlock()
    }

    private static func clearPending() {
        pendingLock.lock()
        pending = nil
        pendingLock.unlock()
    }

    private static func pasteInsert(_ text: String) -> Bool {
        let pb = NSPasteboard.general
        let saved = snapshot(pb)
        guard writeConcealed(text, to: pb) else {
            restore(pb, saved)
            return false
        }
        let stamp = pb.changeCount
        guard postCommandV() else {
            restore(pb, saved)
            return false
        }
        // The paste is asynchronous in the receiving app; restoring immediately
        // would race it.  Half a second is long enough for every app tested and
        // short enough that a real Cmd-V in between is unlikely.
        setPending(pb, saved, stamp)
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.5) {
            flushPendingRestore()
        }
        return true
    }

    /// Headless proof of both rules, run by `--selftest-paste` against a PRIVATE
    /// pasteboard so it cannot disturb what the user has copied.  Returns one
    /// (ok, description) pair per check.
    static func selftestPaste(on pb: NSPasteboard) -> [(ok: Bool, line: String)] {
        var results: [(ok: Bool, line: String)] = []
        func check(_ ok: Bool, _ line: String) { results.append((ok, line)) }
        let secret = "dictated words"

        // 1. the dictated text goes on concealed
        pb.clearContents()
        _ = pb.setString("ORIGINAL", forType: .string)
        let saved = snapshot(pb)
        let wrote = writeConcealed(secret, to: pb)
        let types = pb.pasteboardItems?.first?.types ?? []
        check(wrote && pb.string(forType: .string) == secret,
              "the dictated text is on the pasteboard")
        check(types.contains(concealedType),
              "org.nspasteboard.ConcealedType is declared")
        check(types.contains(autoGeneratedType),
              "org.nspasteboard.AutoGeneratedType is declared")

        // 2. an undisturbed window restores what was there before
        setPending(pb, saved, pb.changeCount)
        flushPendingRestore()
        check(pb.string(forType: .string) == "ORIGINAL",
              "an undisturbed window restores the previous contents")
        check(!hasPendingRestore, "the pending restore is consumed")

        // 3. a copy made inside the window survives — this is H1
        pb.clearContents()
        _ = pb.setString("ORIGINAL", forType: .string)
        let saved2 = snapshot(pb)
        _ = writeConcealed(secret, to: pb)
        setPending(pb, saved2, pb.changeCount)
        pb.clearContents()                                  // the user's own Cmd-C
        _ = pb.setString("USER COPY", forType: .string)
        flushPendingRestore()
        check(pb.string(forType: .string) == "USER COPY",
              "a copy made during the window is not overwritten")
        check(!hasPendingRestore, "the pending restore is consumed either way")

        // 4. a refused insertion leaves the words on the clipboard, concealed
        pb.clearContents()
        _ = pb.setString("ORIGINAL", forType: .string)
        let saved3 = snapshot(pb)
        setPending(pb, saved3, pb.changeCount)
        _ = writeConcealed(secret, to: pb)                   // stands in for offerOnClipboard,
        clearPending()                                       // which writes to .general
        flushPendingRestore()
        check(pb.string(forType: .string) == secret,
              "text offered after a refused insert is not restored away")
        return results
    }

    private static func postCommandV() -> Bool {
        guard let src = CGEventSource(stateID: .combinedSessionState) else { return false }
        let v = CGKeyCode(kVK_ANSI_V)
        guard let down = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: true),
              let up = CGEvent(keyboardEventSource: src, virtualKey: v, keyDown: false)
        else { return false }
        down.flags = .maskCommand
        up.flags = .maskCommand
        down.post(tap: .cghidEventTap)
        up.post(tap: .cghidEventTap)
        return true
    }

    private static func snapshot(_ pb: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        var saved: [[NSPasteboard.PasteboardType: Data]] = []
        for item in pb.pasteboardItems ?? [] {
            var one: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let d = item.data(forType: type) { one[type] = d }
            }
            if !one.isEmpty { saved.append(one) }
        }
        return saved
    }

    private static func restore(_ pb: NSPasteboard, _ saved: [[NSPasteboard.PasteboardType: Data]]) {
        pb.clearContents()
        if saved.isEmpty { return }
        var items: [NSPasteboardItem] = []
        for one in saved {
            let item = NSPasteboardItem()
            for (type, data) in one { item.setData(data, forType: type) }
            items.append(item)
        }
        pb.writeObjects(items)
    }
}

// ---------------------------------------------------------------------------
// menu-bar icon — drawn, not shipped as an asset
// ---------------------------------------------------------------------------
//
// A template image (black + alpha) so macOS tints it for light, dark and the
// highlighted menu-bar state on its own.  Four states, distinguishable at 18pt
// without colour: outline mic (idle), filled mic (listening), mic with three
// dots (cleaning), mic with a slash (error).

enum StatusIcon {
    enum State { case idle, listening, cleaning, error }

    static func image(_ state: State) -> NSImage {
        let size = NSSize(width: 18, height: 18)
        let img = NSImage(size: size, flipped: false) { _ in
            let body = NSBezierPath(roundedRect: NSRect(x: 6.6, y: 6.6, width: 4.8, height: 8.4),
                                    xRadius: 2.4, yRadius: 2.4)
            let cradle = NSBezierPath()
            cradle.appendArc(withCenter: NSPoint(x: 9, y: 7.2), radius: 4.0,
                             startAngle: 200, endAngle: 340, clockwise: true)
            let stem = NSBezierPath()
            stem.move(to: NSPoint(x: 9, y: 3.2))
            stem.line(to: NSPoint(x: 9, y: 1.5))

            NSColor.black.setStroke()
            NSColor.black.setFill()

            switch state {
            case .listening:
                body.fill()
            default:
                body.lineWidth = 1.5
                body.stroke()
            }
            cradle.lineWidth = 1.5
            cradle.lineCapStyle = .round
            cradle.stroke()
            stem.lineWidth = 1.5
            stem.lineCapStyle = .round
            stem.stroke()

            if state == .cleaning {
                for i in 0..<3 {
                    let dot = NSBezierPath(ovalIn: NSRect(x: 13.4, y: 13.2 - Double(i) * 2.6,
                                                          width: 1.8, height: 1.8))
                    dot.fill()
                }
            }
            if state == .error {
                let slash = NSBezierPath()
                slash.move(to: NSPoint(x: 3.4, y: 3.0))
                slash.line(to: NSPoint(x: 14.6, y: 15.4))
                slash.lineWidth = 1.8
                slash.lineCapStyle = .round
                slash.stroke()
            }
            return true
        }
        img.isTemplate = true
        return img
    }
}

