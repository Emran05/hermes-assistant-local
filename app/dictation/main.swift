    FileHandle.standardOutput.write((msg + "\n").data(using: .utf8)!)
}

func nowMs() -> Double { Date().timeIntervalSince1970 * 1000.0 }

/// A lock-guarded value.  The command-line modes hand a result back from a
/// detached `Task` and read it after a semaphore wait that is allowed to TIME
/// OUT — on that path the write and the read genuinely race, and plain captured
/// locals would be read while the Task is still writing them.  Everything the
/// two sides share goes through one of these instead.
final class Guarded<T>: @unchecked Sendable {
    private let lock = NSLock()
    private var stored: T

    init(_ value: T) { stored = value }

    var value: T {
        get { lock.lock(); defer { lock.unlock() }; return stored }
        set { lock.lock(); stored = newValue; lock.unlock() }
    }
}

// ---------------------------------------------------------------------------
// dashboard client — loopback only, no Origin header
// ---------------------------------------------------------------------------
//
// The dashboard's same-origin guard (CLAUDE.md) refuses a *present* cross-origin
// Origin and allows requests that carry none, which is exactly the shape of a
// native client.  We send no Origin, and our Host (127.0.0.1:7788) is in its
// ALLOWED_HOSTS.  Everything here is best-effort: a failure is a log line, never
// a thrown error the dictation path has to handle.

enum Dash {
    /// The only address this helper will ever talk to unless the environment
    /// names another LOOPBACK one.
    static let fallbackBase = "http://127.0.0.1:7788"

    /// Resolved once (a `static let` initialiser is lazy and runs exactly once),
    /// so the refusal below is also logged exactly once.
    static let base: String = resolveBase()

    /// `HERMES_DASH_URL` is a convenience for running against a dashboard on
    /// another port, NOT a redirect: every transcript the helper produces goes
    /// through it, and `openSettings` opens it in a browser.  So it is accepted
    /// only when it is plain `http` to this machine — anything else (https to a
    /// host, a LAN address, `file:`, a bare word) is refused and the default is
    /// used, because a typo or a poisoned environment must not be able to send
    /// what the user just said off this Mac.
    private static func resolveBase() -> String {
        guard let raw = ProcessInfo.processInfo.environment["HERMES_DASH_URL"],
              !raw.isEmpty
        else { return fallbackBase }
        let trimmed = raw.hasSuffix("/") ? String(raw.dropLast()) : raw
        let loopback: Set<String> = ["127.0.0.1", "localhost", "::1"]
        if let url = URL(string: trimmed),
           url.scheme?.lowercased() == "http",
           url.user == nil, url.password == nil,   // `http://looks-real.com@127.0.0.1`
           let host = url.host?.lowercased()
               .trimmingCharacters(in: CharacterSet(charactersIn: "[]")),
           loopback.contains(host) {
            return trimmed
        }
        log("HERMES_DASH_URL=\(trimmed) is not an http:// loopback address — "
            + "ignoring it and using \(fallbackBase)")
        return fallbackBase
    }

    /// Synchronous POST.  Returns the decoded JSON object, or nil on any
    /// failure (connection refused, timeout, non-JSON, non-200).
    @discardableResult
    static func post(_ path: String, _ body: [String: Any], timeout: TimeInterval) -> [String: Any]? {
        guard let url = URL(string: base + path) else { return nil }
        var req = URLRequest(url: url, cachePolicy: .reloadIgnoringLocalCacheData,
                             timeoutInterval: timeout)
        req.httpMethod = "POST"
        req.setValue("application/json", forHTTPHeaderField: "Content-Type")
        req.httpBody = try? JSONSerialization.data(withJSONObject: body, options: [])
        return send(req, timeout: timeout)
    }

    static func get(_ path: String, timeout: TimeInterval) -> [String: Any]? {
        guard let url = URL(string: base + path) else { return nil }
        var req = URLRequest(url: url, cachePolicy: .reloadIgnoringLocalCacheData,
                             timeoutInterval: timeout)
        req.httpMethod = "GET"
        return send(req, timeout: timeout)
    }

    private static func send(_ req: URLRequest, timeout: TimeInterval) -> [String: Any]? {
        let sem = DispatchSemaphore(value: 0)
        var result: [String: Any]?
        let task = URLSession.shared.dataTask(with: req) { data, resp, _ in
            defer { sem.signal() }
            guard let http = resp as? HTTPURLResponse, http.statusCode == 200,
                  let data = data,
                  let obj = try? JSONSerialization.jsonObject(with: data) as? [String: Any]
            else { return }
            result = obj
        }
        task.resume()
        if sem.wait(timeout: .now() + timeout + 1.0) == .timedOut {
            task.cancel()
            return nil
        }
        return result
    }
}

