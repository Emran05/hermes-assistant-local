func runSelftest(_ path: String) -> Int32 {
    let url = URL(fileURLWithPath: (path as NSString).expandingTildeInPath)
    guard FileManager.default.fileExists(atPath: url.path) else {
        out("selftest: no such file: \(url.path)")
        return 2
    }
    let kind = preferredEngine()
    out("engine: \(kind.label)")
    // The Task below writes this and the code after the wait reads it — and the
    // wait is allowed to time out, so the two really can run at once.  Plain
    // locals would be a data race with a 180-second fuse.
    let result = Guarded<(text: String, err: String?, skipped: String?)>(
        (text: "", err: nil, skipped: nil))
    let sem = DispatchSemaphore(value: 0)

    if #available(macOS 26.0, *), kind == .analyzer {
        Task {
            let locale = AnalyzerSupport.locale().identifier(.bcp47)
            // Deliberately NOT an install: a verification run must not pull a
            // speech model over the network, least of all inside the timeout
            // budget below.  A missing asset is a skip, not a failure.
            if await AnalyzerSupport.installed() {
                do {
                    let text = try await AnalyzerSupport.transcribeFile(url, install: false)
                    result.value = (text: text, err: nil, skipped: nil)
                } catch {
                    result.value = (text: "", err: error.localizedDescription, skipped: nil)
                }
            } else {
                result.value = (text: "", err: nil, skipped: locale)
            }
            sem.signal()
        }
    } else {
        LegacyLive.transcribeFile(url) { t, e in
            result.value = (text: t, err: e, skipped: nil)
            sem.signal()
        }
    }
    if sem.wait(timeout: .now() + 180) == .timedOut {
        out("selftest: timed out after 180s")
        return 3
    }
    let got = result.value
    if let locale = got.skipped {
        out("selftest: SKIPPED — the \(locale) speech asset is not installed")
        return 0                       // a skip is not a failure; the line says so
    }
    if let e = got.err, got.text.isEmpty {
        out("selftest: FAILED — \(e)")
        return 1
    }
    out("transcript: \(got.text)")
    return got.text.isEmpty ? 1 : 0
}

/// `--selftest-paste`: the clipboard contract, headless.  Runs against a private
/// pasteboard of its own — never `NSPasteboard.general` — so it can be run at
/// any time without touching what the user has copied.
func runPasteSelftest() -> Int32 {
    let pb = NSPasteboard(name: NSPasteboard.Name("local.hermes.dictation.selftest"))
    let results = Inserter.selftestPaste(on: pb)
    pb.clearContents()
    pb.releaseGlobally()
    var failed = 0
    for r in results {
        out("\(r.ok ? "ok  " : "FAIL") \(r.line)")
        if !r.ok { failed += 1 }
    }
    out("selftest-paste: \(results.count - failed)/\(results.count) checks passed")
    return failed == 0 ? 0 : 1
}

func runProbe() -> Int32 {
    let kind = preferredEngine()
    var payload: [String: Any] = [
        "version": appVersion(),
        "engine": kind.label,
        "mic": Perms.mic().rawValue,
        "accessibility": Perms.accessibility().rawValue,
        "secure_input": Perms.secureInput(),
        "dashboard": Dash.base,
    ]
    payload["timed_out"] = false
    if #available(macOS 26.0, *), kind == .analyzer {
        // Both answers are unknown until the Task fills them in, and the wait can
        // expire.  Reporting a timeout as `false` would state, as fact, that the
        // locale is unsupported and the asset missing — so an unknown stays null
        // and `timed_out` says why.  Guarded, because the Task may still be
        // writing when the wait gives up.
        let sem = DispatchSemaphore(value: 0)
        let answers = Guarded<(supported: Bool?, installed: Bool?)>((nil, nil))
        Task {
            let supported = await AnalyzerSupport.supported()
            let installed = await AnalyzerSupport.installed()
            answers.value = (supported: supported, installed: installed)
            sem.signal()
        }
        let timedOut = sem.wait(timeout: .now() + 30) == .timedOut
        let got = answers.value
        payload["timed_out"] = timedOut
        payload["locale"] = AnalyzerSupport.locale().identifier(.bcp47)
        payload["locale_supported"] = got.supported.map { $0 as Any } ?? NSNull()
        payload["asset_installed"] = got.installed.map { $0 as Any } ?? NSNull()
        payload["speech"] = Perms.speech(engine: kind.label,
                                         assetInstalled: got.installed).rawValue
    } else {
        payload["speech"] = Perms.speech(engine: kind.label, assetInstalled: nil).rawValue
    }
    let data = (try? JSONSerialization.data(withJSONObject: payload,
                                            options: [.prettyPrinted, .sortedKeys])) ?? Data()
    out(String(data: data, encoding: .utf8) ?? "{}")
    return 0
}

